#include<iostream>
#include<cstdio>
using namespace std;
double n,p,l,r;
signed main()
{
	scanf("%lf%lf%lf%lf",&n,&p,&l,&r);
	printf("%0.7lf",(r-l+1)*p);
}
/*
思路总结
1. 几何分布与二项分布含义，对应题干随机变量
    - 几何分布：X_j 需要做多少次试验才能迎来下一次成功,规则：前面连续全部失败，最后一次成功。比如X_j=5，代表连续失败4次，第5次试验成功，对应的概率就是(1-p)^4×p
    - 二项分布：固定一共做M次试验，每次试验独立，成功概率p。统计这M次里，一共能成功多少次。这是后面做事件等价转换才用到的，不是题目一开始的X。
2. 理解前缀和Y_j的物理意义
    Y_j=X_1+X_2+…+X_j，也就是X数列的前缀和。
    含义：从头开始，一直到拿到**第j次成功**，全部试验次数加起来，一共做了多少次试验。
3. 概率差分思想（F(r)-F(l-1)）
4. 化简条件
    当r<=n时，M次试验最多成功M次，一定不会超过n。此时大F(M)就等于M*p
    代入差分：答案=rp-(l-1)p=p(r-l+1)
*/